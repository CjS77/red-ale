#!/usr/bin/env python3
"""Generate crates/red-ale-core/src/iso4217_table.rs from GnuCash's iso-4217-currencies.xml.

Usage: scripts/gen-iso4217.py "$GNUCASH_SOURCE/libgnucash/engine/iso-4217-currencies.xml"
"""
import sys
import xml.etree.ElementTree as ET

src = sys.argv[1]
root = ET.parse(src).getroot()
rows = []
for c in root.findall("currency"):
    a = c.attrib
    rows.append((a["isocode"], a["fullname"], a["exchange-code"], int(a["smallest-fraction"]), a.get("local-symbol", "")))

def lit(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

out = [
    "//! The ISO 4217 currency table GnuCash 5.17 loads into every book.",
    "//!",
    "//! Generated by `scripts/gen-iso4217.py` from `5.17:libgnucash/engine/iso-4217-currencies.xml`",
    "//! (GPL-2.0-or-later, Copyright (C) the GnuCash developers). Do not edit by hand.",
    "",
    "/// One built-in currency: ISO code, full name, ISO numeric code, smallest fraction and local symbol.",
    "pub(crate) const CURRENCIES: [(&str, &str, &str, i64, &str); %d] = [" % len(rows),
]
out += ["    (%s, %s, %s, %d, %s)," % (lit(r[0]), lit(r[1]), lit(r[2]), r[3], lit(r[4])) for r in rows]
out.append("];")
print("\n".join(out))
